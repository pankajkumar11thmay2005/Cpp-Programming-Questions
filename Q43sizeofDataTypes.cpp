#include <iostream>
using namespace std;

int main() {
  cout << sizeof(char) << endl; // Size of char
  cout << sizeof(short) << endl; // Size of short   
  cout << sizeof(int) << endl; // Size of int
  cout << sizeof(long) << endl; // Size of long
  cout << sizeof(long long) << endl; // Size of long long
  cout << sizeof(float) << endl; // Size of float
  cout << sizeof(double) << endl; // Size of double
  return 0;
}